// Generate agent/apps/cyberchef/operations.js from the vendored CyberChef release:
// the operation names of public/pc/vendor/cyberchef (v11.5.0). The registry appears in
// assets/main.js twice - once as an object literal and once as a JSON-escaped string
// constant (names with non-ASCII characters are \u-escaped there) - so both forms are
// collected and JSON-decoded. Grep markers: the entries are "<Name>":{"module":"...","description":.
// Re-run after a vendor bump: node scripts/agent/generate-cyberchef-ops.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const MAIN = join(ROOT, 'public/pc/vendor/cyberchef/assets/main.js');
const OUT = join(ROOT, 'agent/apps/cyberchef/operations.js');

const src = readFileSync(MAIN, 'utf8');
const names = new Map();
const add = raw => {
  const name = JSON.parse('"' + raw + '"');
  names.set(name, (names.get(name) ?? 0) + 1);
};
// Unescaped object-literal form: "<Name>":{"module":"...","description":
for (const m of src.matchAll(/"((?:[^"\\]|\\.)+)":\{"module":"[^"]*","description":/g)) add(m[1]);
// Escaped-string form: \"<Name>\":{\"module\":
for (const m of src.matchAll(/\\"((?:[^"\\]|\\\\.)+)\\":\{\\"module\\":"/g)) add(m[1]);

const list = [...names.keys()].sort();
if (list.length < 100) throw new Error(`extracted ${list.length} operation names - the vendor layout changed`);
const body = `// Generated by scripts/agent/generate-cyberchef-ops.mjs from the vendored CyberChef\n// release (public/pc/vendor/cyberchef, v11.5.0): every operation name the registry\n// exposes, so find_tool ranks cyberchef.bake first for an inner operation name (A4).\n// Do not edit by hand; re-run the generator after a vendor bump.\nexport const OPERATION_NAMES = ${JSON.stringify(list, null, 2).replace(/\n/g, '\n')};\n`;
writeFileSync(OUT, body);
console.log(`operations.js: ${list.length} names -> ${OUT}`);
