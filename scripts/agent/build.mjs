// Build Buddy's tool catalog and skill wiki from the agent packs (plan section 4).
//   agent/system, agent/desktop, agent/files   always on
//   agent/apps/<app-id>                        only for catalog apps with enabled: true
// Each pack may have tools.js (joins the tool catalog) and skills.md (joins the skill wiki).
// Output goes to src/apps/ai-agent/generated/ (gitignored); `npm run catalog` runs this.
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { loadCatalog, ROOT } from '../catalog/catalog.mjs';
import { buildCatalog } from '../../src/apps/ai-agent/runtime/catalog.mjs';
import { parseSkills, checkSkills } from '../../src/apps/ai-agent/runtime/skills.mjs';
import { checkArgs } from '../../src/apps/ai-agent/runtime/args.mjs';
import { buildIndex } from '../../src/apps/ai-agent/runtime/search.mjs';

export const CORE_PACKS = ['system', 'desktop', 'files'];
export const GENERATED = 'src/apps/ai-agent/generated';

/** Packs present on disk: [{ id, dir, tools?, skills? }]. Unknown app ids are errors; disabled apps are skipped. */
export function discoverPacks(root, catalog) {
  const packs = []; const errors = [];
  const add = (id, dir) => {
    const tools = existsSync(join(dir, 'tools.js')) ? join(dir, 'tools.js') : null;
    const skills = existsSync(join(dir, 'skills.md')) ? join(dir, 'skills.md') : null;
    if (tools || skills) packs.push({ id, dir, tools, skills });
  };
  for (const id of CORE_PACKS) if (existsSync(join(root, 'agent', id))) add(id, join(root, 'agent', id));
  const appsDir = join(root, 'agent', 'apps');
  if (existsSync(appsDir)) for (const id of readdirSync(appsDir).sort()) {
    const app = catalog.apps.find(a => a.id === id);
    if (!app) { errors.push(`agent/apps/${id}: no app "${id}" in catalog.yaml`); continue; }
    if (app.enabled) add(id, join(appsDir, id));
  }
  return { packs, errors };
}

/** Validate every pack and write the generated catalog, wiki and search indexes. Throws listing every defect. */
export async function buildAgent(root = ROOT, { write = true } = {}) {
  const catalog = loadCatalog(root);
  const appIds = catalog.apps.filter(a => a.enabled && a.kind !== 'panel').map(a => a.id);
  const choices = name => (name === 'apps' || name === 'windows' ? appIds : []);
  const { packs, errors } = discoverPacks(root, catalog);
  const modules = [];
  for (const p of packs.filter(p => p.tools)) {
    const mod = await import(pathToFileURL(p.tools).href);
    if (mod.pack?.id !== p.id) { errors.push(`${relative(root, p.tools)}: export const pack = { id: '${p.id}', ... } is required`); continue; }
    for (const t of mod.tools ?? []) {
      if (typeof t.run !== 'function') errors.push(`${t.name}: run must be a function`);
      for (const k of ['purpose', 'when']) if (typeof t[k] !== 'string' || !t[k].trim()) errors.push(`${t.name}: ${k} is required`);
    }
    modules.push({ pack: mod.pack, tools: mod.tools ?? [] });
  }
  const cat = buildCatalog(modules, { choices });
  errors.push(...cat.errors);
  const skills = [];
  for (const p of packs.filter(p => p.skills)) {
    const parsed = parseSkills(readFileSync(p.skills, 'utf8'), p.id);
    errors.push(...parsed.errors.map(e => `${relative(root, p.skills)}: ${e}`));
    skills.push(...parsed.skills);
  }
  errors.push(...checkSkills(skills, name => cat.tools.get(name), { checkArgs: (tool, raw) => checkArgs(tool, raw, { choices }) }));
  if (errors.length) throw new Error(`agent packs have ${errors.length} problem(s):\n  ${errors.join('\n  ')}`);

  const tools = [...cat.tools.values()].map(({ run, ...t }) => ({ ...t, pack: t.name.split('.')[0] }));
  const skillDocs = skills.map(s => ({ id: s.path, path: s.path, title: s.title, summary: s.summary, keywords: s.keywords, body: [s.when, ...s.steps.map(st => st.line), s.check, s.gotchas].filter(Boolean).join('\n') }));
  const out = {
    'catalog.json': JSON.stringify({ tools, docs: cat.docs, apps: catalog.apps.filter(a => a.enabled && a.kind !== 'panel').map(a => ({ id: a.id, title: a.title, category: a.category })) }),
    'skills.json': JSON.stringify(skills),
    'search-tools.json': buildIndex(cat.docs, { store: ['name', 'purpose'] }),
    'search-skills.json': buildIndex(skillDocs, { store: ['path', 'title', 'summary'] }),
    'packs.mjs': `// Generated by scripts/agent/build.mjs. Each enabled pack's tools.js, loaded on first use.\nexport const packs = {\n${modules.map(m => `  ${JSON.stringify(m.pack.id)}: () => import(${JSON.stringify(relative(join(root, GENERATED), packs.find(p => p.id === m.pack.id).tools))}),`).join('\n')}\n};\n`,
    'INDEX.md': `# Buddy skill wiki index (generated)\n\n| Path | Title | Summary | Keywords |\n|---|---|---|---|\n${skills.map(s => `| ${s.path} | ${s.title} | ${s.summary} | ${s.keywords.join(', ')} |`).join('\n')}\n`,
  };
  if (write) {
    const dir = join(root, GENERATED);
    rmSync(dir, { recursive: true, force: true }); mkdirSync(dir, { recursive: true });
    for (const [name, text] of Object.entries(out)) writeFileSync(join(dir, name), text);
  }
  return { packs: modules.length, tools: tools.length, skills: skills.length, out };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const r = await buildAgent();
  console.log(`agent packs valid: ${r.tools} tools in ${r.packs} packs, ${r.skills} skills.`);
}
